package orbit.protocolgen;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.Comparator;
import java.util.HexFormat;
import java.util.stream.Stream;

/**
 * Generates Java protocol classes from the parser JSON.
 *
 * <pre>
 *   GeneratorMain &lt;protocol dir with packets-*.json and meta-*.json&gt; &lt;output source dir&gt; [&lt;older protocols dir&gt;]
 * </pre>
 * The newest {@code meta-*.json} selects the packets file via its {@code "packets"} field. With a third directory each
 * earlier protocol (another {@code versionHash}: the wire changed, ids and field order) is generated there too, the newest
 * build of each into {@code orbit.protocol.old.b<build>}, with {@code orbit.protocol.old.Legacy} listing them — the
 * tests read recordings of earlier client builds by them.
 */
public final class GeneratorMain {

    private GeneratorMain() {
    }

    public static void main(String[] args) throws Exception {
        if (args.length != 2 && args.length != 3) {
            System.err.println("usage: GeneratorMain <protocol dir> <output dir> [<older protocols dir>]");
            System.exit(2);
        }
        Path protocolDir = Path.of(args[0]);
        Path outDir = Path.of(args[1]);

        Path metaFile = newest(protocolDir, "meta-");
        ObjectMapper om = new ObjectMapper();
        JsonNode meta = om.readTree(metaFile.toFile());
        Path packetsFile = protocolDir.resolve(meta.get("packets").asText());
        byte[] packetsBytes = Files.readAllBytes(packetsFile);
        JsonNode packets = om.readTree(packetsBytes);

        ProtocolModel model = ProtocolModel.from(packets);
        String jsonSha = HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(packetsBytes));

        Path pkgDir = outDir.resolve(JavaEmitter.PACKAGE.replace('.', '/'));
        clean(outDir);
        Files.createDirectories(pkgDir);
        JavaEmitter emitter = new JavaEmitter(model);
        for (ProtocolModel.Module m : model.modules()) {
            write(pkgDir.resolve(m.name() + ".java"), emitter.module(m));
        }
        write(pkgDir.resolve("Packets.java"), emitter.registry());
        write(pkgDir.resolve("ProtocolVersion.java"), emitter.version(meta, packetsFile.getFileName().toString(), jsonSha));
        System.out.printf("Сгенерировано %d классов пакетов из %s (сборка %s)%n",
                model.modules().size(), packetsFile.getFileName(), meta.path("build").asText());
        if (args.length == 3) {
            older(protocolDir, Path.of(args[2]), meta.path("versionHash").asText(), om);
        }
    }

    /** Each earlier wire (versionHash) once, by its newest build, and the {@code Legacy} index of them. */
    private static void older(Path protocolDir, Path outDir, String currentHash, ObjectMapper om) throws Exception {
        java.util.Map<String, Path> byHash = new java.util.TreeMap<>();
        java.util.Map<String, JsonNode> metas = new java.util.TreeMap<>();
        try (Stream<Path> s = Files.list(protocolDir)) {
            for (Path p : s.filter(p -> p.getFileName().toString().startsWith("meta-") && p.toString().endsWith(".json"))
                    .sorted().toList()) {
                JsonNode m = om.readTree(p.toFile());
                String hash = m.path("versionHash").asText();
                if (!hash.isEmpty() && !hash.equals(currentHash)) {
                    byHash.put(hash, p); // sorted by date: the newest of a hash wins
                    metas.put(hash, m);
                }
            }
        }
        clean(outDir);
        StringBuilder index = new StringBuilder();
        index.append("// Generated by protocol-gen. Do not edit.\n");
        index.append("package ").append(JavaEmitter.OLD_PACKAGE).append(";\n\n");
        index.append("/** Earlier protocols, one per {@code versionHash}: recordings of earlier client builds are read by them. */\n");
        index.append("public final class Legacy {\n\n");
        index.append("    public record Protocol(java.lang.String versionHash, java.lang.String build, java.lang.String pkg,\n");
        index.append("                           orbit.protocol.Registry registry) {\n    }\n\n");
        index.append("    public static final java.util.List<Protocol> ALL = java.util.List.of(");
        boolean first = true;
        for (var e : byHash.entrySet()) {
            JsonNode meta = metas.get(e.getKey());
            String build = meta.path("build").asText().replaceAll("[^0-9A-Za-z]", "");
            String pkg = JavaEmitter.OLD_PACKAGE + ".b" + build;
            Path packetsFile = protocolDir.resolve(meta.get("packets").asText());
            byte[] bytes = Files.readAllBytes(packetsFile);
            ProtocolModel model = ProtocolModel.from(om.readTree(bytes));
            String sha = HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes));
            Path dir = outDir.resolve(pkg.replace('.', '/'));
            Files.createDirectories(dir);
            JavaEmitter emitter = new JavaEmitter(model, pkg);
            for (ProtocolModel.Module m : model.modules()) {
                write(dir.resolve(m.name() + ".java"), emitter.module(m));
            }
            write(dir.resolve("Packets.java"), emitter.registry());
            write(dir.resolve("ProtocolVersion.java"), emitter.version(meta, packetsFile.getFileName().toString(), sha));
            index.append(first ? "\n" : ",\n").append("        new Protocol(\"").append(e.getKey()).append("\", \"")
                    .append(build).append("\", \"").append(pkg).append("\", ").append(pkg).append(".Packets.REGISTRY)");
            first = false;
            System.out.printf("Старый протокол: %d классов из %s (сборка %s) в %s%n", model.modules().size(),
                    packetsFile.getFileName(), build, pkg);
        }
        index.append(");\n\n    private Legacy() {\n    }\n}\n");
        Path dir = outDir.resolve(JavaEmitter.OLD_PACKAGE.replace('.', '/'));
        Files.createDirectories(dir);
        write(dir.resolve("Legacy.java"), index.toString());
    }

    private static Path newest(Path dir, String prefix) throws IOException {
        try (Stream<Path> s = Files.list(dir)) {
            return s.filter(p -> p.getFileName().toString().startsWith(prefix) && p.toString().endsWith(".json"))
                    .max(Comparator.comparing(p -> p.getFileName().toString()))
                    .orElseThrow(() -> new IOException("no " + prefix + "*.json in " + dir));
        }
    }

    private static void clean(Path dir) throws IOException {
        if (!Files.exists(dir)) {
            return;
        }
        try (Stream<Path> s = Files.walk(dir)) {
            for (Path p : s.sorted(Comparator.reverseOrder()).toList()) {
                Files.delete(p);
            }
        }
    }

    private static void write(Path file, String content) throws IOException {
        Files.writeString(file, content, StandardCharsets.UTF_8);
    }
}
