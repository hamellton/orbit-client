package orbit.protocolgen;

import com.fasterxml.jackson.databind.JsonNode;
import java.util.LinkedHashSet;
import java.util.Set;
import orbit.protocolgen.ProtocolModel.Kind;
import orbit.protocolgen.ProtocolModel.Module;
import orbit.protocolgen.ProtocolModel.Prim;
import orbit.protocolgen.ProtocolModel.Step;

/**
 * Emits Java source for the protocol model.
 *
 * <p>Generated classes mirror the client's inheritance. Field (de)serialisation lives in
 * static {@code writeFields}/{@code readFields} methods so that a parent's body can be invoked
 * for a subclass instance without virtual dispatch. Type names inside method bodies are fully
 * qualified because a field may share its name with a class.
 */
final class JavaEmitter {

    static final String PACKAGE = "orbit.protocol.gen";
    private static final String RT = "orbit.protocol.";

    private final ProtocolModel model;

    JavaEmitter(ProtocolModel model) {
        this.model = model;
    }

    String module(Module m) {
        String fq = PACKAGE + "." + m.name();
        String superclass = m.parent() != null ? PACKAGE + "." + m.parent() : RT + "AbstractPacket";
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by protocol-gen. Do not edit.\n");
        sb.append("package ").append(PACKAGE).append(";\n\n");
        sb.append("@SuppressWarnings(\"all\")\n");
        sb.append("public class ").append(m.name()).append(" extends ").append(superclass).append(" {\n\n");
        sb.append("    public static final short MODULE_ID = ").append(m.id()).append(";\n\n");

        Set<String> declared = new LinkedHashSet<>();
        for (Step s : m.steps()) {
            if (s.kind() == Kind.SUPER || !declared.add(s.field())) {
                continue;
            }
            sb.append("    public ").append(fieldType(s)).append(' ').append(s.field());
            String init = initialValue(s);
            if (init != null) {
                sb.append(" = ").append(init);
            }
            sb.append(";\n");
        }
        if (!declared.isEmpty()) {
            sb.append('\n');
        }

        sb.append("    @Override\n    public short moduleId() {\n        return MODULE_ID;\n    }\n\n");
        sb.append("    @Override\n    public void write(").append(RT).append("PacketOutput out) {\n")
                .append("        out.writeShort(MODULE_ID);\n")
                .append("        writeFields(this, out);\n    }\n\n");
        sb.append("    public static ").append(fq).append(" read(").append(RT).append("PacketInput in) {\n")
                .append("        ").append(fq).append(" p = new ").append(fq).append("();\n")
                .append("        readFields(p, in);\n        return p;\n    }\n\n");

        sb.append("    static void writeFields(").append(fq).append(" p, ").append(RT).append("PacketOutput out) {\n");
        for (Step s : m.steps()) {
            sb.append(writeStep(s));
        }
        sb.append("    }\n\n");

        sb.append("    static void readFields(").append(fq).append(" p, ").append(RT).append("PacketInput in) {\n");
        for (Step s : m.steps()) {
            sb.append(readStep(s));
        }
        sb.append("    }\n}\n");
        return sb.toString();
    }

    private static String fieldType(Step s) {
        return switch (s.kind()) {
            case PRIMITIVE -> primType(s.prim());
            case MODULE -> moduleType(s.moduleType());
            case PRIMITIVE_ARRAY -> "java.util.List<" + boxed(s.prim()) + ">";
            case MODULE_ARRAY -> "java.util.List<" + moduleType(s.moduleType()) + ">";
            case SUPER -> throw new IllegalStateException();
        };
    }

    private static String initialValue(Step s) {
        return switch (s.kind()) {
            case PRIMITIVE -> s.prim() == Prim.UTF ? "\"\"" : null;
            case PRIMITIVE_ARRAY, MODULE_ARRAY -> "new java.util.ArrayList<>()";
            default -> null;
        };
    }

    private static String moduleType(String name) {
        return name == null ? RT + "Packet" : PACKAGE + "." + name;
    }

    private static String primType(Prim p) {
        return switch (p) {
            case INT -> "int";
            case SHORT -> "short";
            case BYTE -> "byte";
            case BOOLEAN -> "boolean";
            case DOUBLE -> "double";
            case FLOAT -> "float";
            case UTF -> "java.lang.String";
        };
    }

    private static String boxed(Prim p) {
        return switch (p) {
            case INT -> "java.lang.Integer";
            case SHORT -> "java.lang.Short";
            case BYTE -> "java.lang.Byte";
            case BOOLEAN -> "java.lang.Boolean";
            case DOUBLE -> "java.lang.Double";
            case FLOAT -> "java.lang.Float";
            case UTF -> "java.lang.String";
        };
    }

    private static String lengthType(Prim p) {
        return RT + "LengthType." + switch (p) {
            case INT -> "INT";
            case SHORT -> "SHORT";
            case BYTE -> "BYTE";
            default -> throw new IllegalArgumentException("bad length type " + p);
        };
    }

    private static String writePrim(Prim p, int rot, String expr) {
        if (rot != 0) {
            return switch (p) {
                case INT -> "out.writeIntRot(" + expr + ", " + rot + ")";
                case SHORT -> "out.writeShortRot(" + expr + ", " + rot + ")";
                case BYTE -> "out.writeByteRot(" + expr + ", " + rot + ")";
                default -> throw new IllegalArgumentException("rotation on " + p);
            };
        }
        return switch (p) {
            case INT -> "out.writeInt(" + expr + ")";
            case SHORT -> "out.writeShort(" + expr + ")";
            case BYTE -> "out.writeByte(" + expr + ")";
            case BOOLEAN -> "out.writeBoolean(" + expr + ")";
            case DOUBLE -> "out.writeDouble(" + expr + ")";
            case FLOAT -> "out.writeFloat(" + expr + ")";
            case UTF -> "out.writeUTF(" + expr + ")";
        };
    }

    private static String readPrim(Prim p, int rot) {
        if (rot != 0) {
            return switch (p) {
                case INT -> "in.readIntRot(" + rot + ")";
                case SHORT -> "in.readShortRot(" + rot + ")";
                case BYTE -> "in.readByteRot(" + rot + ")";
                default -> throw new IllegalArgumentException("rotation on " + p);
            };
        }
        return switch (p) {
            case INT -> "in.readInt()";
            case SHORT -> "in.readShort()";
            case BYTE -> "in.readByte()";
            case BOOLEAN -> "in.readBoolean()";
            case DOUBLE -> "in.readDouble()";
            case FLOAT -> "in.readFloat()";
            case UTF -> "in.readUTF()";
        };
    }

    private static String writeStep(Step s) {
        String f = "p." + s.field();
        return switch (s.kind()) {
            case SUPER -> "        out.writeShort(" + PACKAGE + "." + s.moduleType() + ".MODULE_ID);\n"
                    + "        " + PACKAGE + "." + s.moduleType() + ".writeFields(p, out);\n";
            case PRIMITIVE -> "        " + writePrim(s.prim(), s.rotateLeft(), f) + ";\n";
            case MODULE -> "        out.writeModule(" + f + ");\n";
            case PRIMITIVE_ARRAY -> "        out.writeLength(" + f + ", " + lengthType(s.lengthType()) + ");\n"
                    + "        if (" + f + " != null) {\n"
                    + "            for (" + boxed(s.prim()) + " e : " + f + ") {\n"
                    + "                " + writePrim(s.prim(), s.rotateLeft(), "e") + ";\n"
                    + "            }\n        }\n";
            case MODULE_ARRAY -> "        out.writeLength(" + f + ", " + lengthType(s.lengthType()) + ");\n"
                    + "        if (" + f + " != null) {\n"
                    + "            for (" + RT + "Packet e : " + f + ") {\n"
                    + "                out.writeModule(e);\n"
                    + "            }\n        }\n";
        };
    }

    private static String readStep(Step s) {
        String f = "p." + s.field();
        return switch (s.kind()) {
            case SUPER -> "        in.expectId(" + PACKAGE + "." + s.moduleType() + ".MODULE_ID);\n"
                    + "        " + PACKAGE + "." + s.moduleType() + ".readFields(p, in);\n";
            case PRIMITIVE -> "        " + f + " = " + readPrim(s.prim(), s.rotateLeft()) + ";\n";
            case MODULE -> "        " + f + " = in.readModule(" + moduleType(s.moduleType()) + ".class);\n";
            case PRIMITIVE_ARRAY -> "        {\n"
                    + "            int n = in.readLength(" + lengthType(s.lengthType()) + ");\n"
                    + "            " + f + " = new java.util.ArrayList<>(Math.min(n, 64));\n"
                    + "            for (int i = 0; i < n; i++) {\n"
                    + "                " + f + ".add(" + readPrim(s.prim(), s.rotateLeft()) + ");\n"
                    + "            }\n        }\n";
            case MODULE_ARRAY -> "        {\n"
                    + "            int n = in.readLength(" + lengthType(s.lengthType()) + ");\n"
                    + "            " + f + " = new java.util.ArrayList<>(Math.min(n, 64));\n"
                    + "            for (int i = 0; i < n; i++) {\n"
                    + "                " + f + ".add(in.readModule(" + moduleType(s.moduleType()) + ".class));\n"
                    + "            }\n        }\n";
        };
    }

    String registry() {
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by protocol-gen. Do not edit.\n");
        sb.append("package ").append(PACKAGE).append(";\n\n");
        sb.append("/** Module id to class registry. */\n");
        sb.append("public final class Packets {\n\n");
        sb.append("    public static final int COUNT = ").append(model.modules().size()).append(";\n\n");
        sb.append("    private static final short[] IDS = {");
        for (int i = 0; i < model.modules().size(); i++) {
            sb.append(i % 16 == 0 ? "\n        " : " ").append(model.modules().get(i).id()).append(',');
        }
        sb.append("\n    };\n\n");
        sb.append("    private Packets() {\n    }\n\n");
        sb.append("    /** All known module ids. */\n");
        sb.append("    public static short[] ids() {\n        return IDS.clone();\n    }\n\n");
        sb.append("    /** Reads the fields of the module with the given id (the id itself is already consumed). */\n");
        sb.append("    public static ").append(RT).append("Packet readBody(short id, ").append(RT)
                .append("PacketInput in) {\n        return switch (id) {\n");
        for (Module m : model.modules()) {
            sb.append("            case ").append(m.id()).append(" -> ").append(PACKAGE).append('.')
                    .append(m.name()).append(".read(in);\n");
        }
        sb.append("            default -> throw new orbit.net.ProtocolException(\"unknown module id \" + id);\n");
        sb.append("        };\n    }\n\n");
        sb.append("    /** Class name for the id, or {@code null} if unknown. */\n");
        sb.append("    public static java.lang.String name(short id) {\n        return switch (id) {\n");
        for (Module m : model.modules()) {
            sb.append("            case ").append(m.id()).append(" -> \"").append(m.name()).append("\";\n");
        }
        sb.append("            default -> null;\n        };\n    }\n\n");
        sb.append("    public static boolean known(short id) {\n        return name(id) != null;\n    }\n}\n");
        return sb.toString();
    }

    String version(JsonNode meta, String packetsFile, String jsonSha) {
        return "// Generated by protocol-gen. Do not edit.\n"
                + "package " + PACKAGE + ";\n\n"
                + "/** Client build this protocol was generated from. */\n"
                + "public final class ProtocolVersion {\n\n"
                + "    public static final java.lang.String CLIENT_VERSION = " + lit(meta.path("clientVersion").asText()) + ";\n"
                + "    public static final java.lang.String BUILD = " + lit(meta.path("build").asText()) + ";\n"
                + "    /** Sent in {@code VersionRequest}; the server answers {@code equal=false} when it is outdated. */\n"
                + "    public static final java.lang.String VERSION_HASH = " + lit(meta.path("versionHash").asText()) + ";\n"
                + "    /** Value of {@code LoginRequest.version} that enables downstream compression. */\n"
                + "    public static final java.lang.String COMPRESSION = " + lit(meta.path("compression").asText()) + ";\n"
                + "    public static final java.lang.String PACKETS_JSON = " + lit(packetsFile) + ";\n"
                + "    public static final java.lang.String PACKETS_JSON_SHA256 = " + lit(jsonSha) + ";\n"
                + "    public static final int PACKET_COUNT = " + model.modules().size() + ";\n\n"
                + "    private ProtocolVersion() {\n    }\n}\n";
    }

    private static String lit(String s) {
        if (!s.matches("[A-Za-z0-9._:+\\-TZ]*")) {
            throw new IllegalArgumentException("unexpected characters in meta value: " + s);
        }
        return '"' + s + '"';
    }
}
